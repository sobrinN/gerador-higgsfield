use crate::json::JsonValue;

#[derive(Debug, Clone)]
pub struct FieldOption {
    pub label: &'static str,
    pub value: &'static str,
}

#[derive(Debug, Clone)]
pub struct ModelField {
    pub name: &'static str,
    pub label: &'static str,
    pub field_type: &'static str, // "textarea", "text", "number", "select", "boolean", "image_url", "image_urls", "video_url", "audio_url"
    pub required: bool,
    pub default_value: JsonValue,
    pub description: &'static str,
    pub options: Option<Vec<FieldOption>>,
    pub min: Option<f64>,
    pub max: Option<f64>,
    pub step: Option<f64>,
}

impl ModelField {
    pub fn to_json(&self) -> JsonValue {
        let mut obj = JsonValue::obj();
        obj.insert("name", JsonValue::Str(self.name.to_string()));
        obj.insert("label", JsonValue::Str(self.label.to_string()));
        obj.insert("field_type", JsonValue::Str(self.field_type.to_string()));
        obj.insert("required", JsonValue::Bool(self.required));
        obj.insert("default_value", self.default_value.clone());
        obj.insert("description", JsonValue::Str(self.description.to_string()));
        if let Some(ref opts) = self.options {
            let mut arr = JsonValue::arr();
            for o in opts {
                let mut o_obj = JsonValue::obj();
                o_obj.insert("label", JsonValue::Str(o.label.to_string()));
                o_obj.insert("value", JsonValue::Str(o.value.to_string()));
                arr.push(o_obj);
            }
            obj.insert("options", arr);
        }
        if let Some(m) = self.min {
            obj.insert("min", JsonValue::Number(m));
        }
        if let Some(m) = self.max {
            obj.insert("max", JsonValue::Number(m));
        }
        if let Some(s) = self.step {
            obj.insert("step", JsonValue::Number(s));
        }
        obj
    }
}

#[derive(Debug, Clone)]
pub struct ModelEntry {
    pub id: &'static str,
    pub endpoint: &'static str,
    pub name: &'static str,
    pub provider: &'static str,
    pub category: &'static str, // "video", "edit", "image", "character", "audio"
    pub badge: &'static str,
    pub pricing_hint: &'static str,
    pub description: &'static str,
    pub doc_url: &'static str,
    pub verified_schema: bool,
    pub verification_note: &'static str,
    pub fields: Vec<ModelField>,
}

impl ModelEntry {
    pub fn to_json(&self) -> JsonValue {
        let mut obj = JsonValue::obj();
        obj.insert("id", JsonValue::Str(self.id.to_string()));
        obj.insert("endpoint", JsonValue::Str(self.endpoint.to_string()));
        obj.insert("name", JsonValue::Str(self.name.to_string()));
        obj.insert("provider", JsonValue::Str(self.provider.to_string()));
        obj.insert("category", JsonValue::Str(self.category.to_string()));
        obj.insert("badge", JsonValue::Str(self.badge.to_string()));
        obj.insert("pricing_hint", JsonValue::Str(self.pricing_hint.to_string()));
        obj.insert("description", JsonValue::Str(self.description.to_string()));
        obj.insert("doc_url", JsonValue::Str(self.doc_url.to_string()));
        obj.insert("verified_schema", JsonValue::Bool(self.verified_schema));
        obj.insert(
            "verification_note",
            JsonValue::Str(self.verification_note.to_string()),
        );
        let mut f_arr = JsonValue::arr();
        for f in &self.fields {
            f_arr.push(f.to_json());
        }
        obj.insert("fields", f_arr);
        obj
    }
}

fn opt(label: &'static str, value: &'static str) -> FieldOption {
    FieldOption { label, value }
}

fn s(val: &str) -> JsonValue {
    JsonValue::Str(val.to_string())
}

